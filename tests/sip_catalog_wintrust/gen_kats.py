#!/usr/bin/env python3
"""Regenerates kats.h: compiles sip_images.h natively, dumps the images and computes their Authenticode
digests with an independent python implementation.   usage: python3 gen_kats.py > kats.h"""
import hashlib, os, struct, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
DUMP = r"""#include <stdio.h>
#include "sip_images.h"
int main(void){ u8 b[4096]; char n[64]; for(unsigned v=0;v<SIPI_PE_NVARIANTS;v++){ size_t s=sipi_pe(v,b,sizeof b); sprintf(n,"pe%u.bin",v); FILE*f=fopen(n,"wb"); fwrite(b,1,s,f); fclose(f);} return 0; }"""
tmp = tempfile.mkdtemp()
open(os.path.join(tmp, "dump.c"), "w").write(DUMP)
subprocess.check_call(["gcc", "-I" + HERE, "-o", os.path.join(tmp, "dump"), os.path.join(tmp, "dump.c")])
subprocess.check_call([os.path.join(tmp, "dump")], cwd=tmp)
os.chdir(tmp)
def ac(d, alg):
    lf=struct.unpack_from('<I',d,0x3c)[0]; nsec=struct.unpack_from('<H',d,lf+6)[0]
    oh=lf+24; chk=oh+64; cd=oh+112+32; soh=struct.unpack_from('<I',d,oh+60)[0]
    cert_off,cert_sz=struct.unpack_from('<II',d,cd)
    h=hashlib.new(alg)
    h.update(d[:chk]); h.update(d[chk+4:cd]); h.update(d[cd+8:soh])
    secs=[]
    for i in range(nsec):
        s=oh+240+40*i; rs,ro=struct.unpack_from('<II',d,s+16); secs.append((ro,rs))
    secs.sort(); pos=soh
    for ro,rs in secs: h.update(d[ro:ro+rs]); pos=ro+rs
    end=cert_off if cert_off else len(d)
    h.update(d[pos:end])
    return h.hexdigest()
def carr(hexs):
    b=bytes.fromhex(hexs); return "{"+",".join("0x%02x"%x for x in b)+"}"
algs=[('sha1','SHA1'),('sha256','SHA256'),('sha384','SHA384'),('sha512','SHA512'),('md5','MD5')]
print("/* generated by gen_kats.py: Authenticode digests of the hand-built images (independent implementation) */")
for v in range(4):
    d=open('pe%d.bin'%v,'rb').read()
    for a,N in algs:
        print("static const unsigned char kat_pe%d_%s[] = %s;"%(v,a,carr(ac(d,a))))
