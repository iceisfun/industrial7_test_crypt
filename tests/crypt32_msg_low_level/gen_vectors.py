#!/usr/bin/env python3
# Authoring-time generator for vectors.h (fixed keys, certs, openssl-made CMS messages). Output is checked in.
import datetime, subprocess, os, tempfile, hashlib
from cryptography import x509
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa, padding

D = datetime.datetime
CONTENT = b"CryptT message content 0123456789"
out = []
def arr(name, b):
    out.append("static const unsigned char %s[] = {%s};\n#define %s_LEN %d" % (
        name, ",".join("0x%02x" % x for x in b), name, len(b)))
def name(cn): return x509.Name([x509.NameAttribute(NameOID.ORGANIZATION_NAME, "CryptT"), x509.NameAttribute(NameOID.COMMON_NAME, cn)])
def der(o): return o.public_bytes(serialization.Encoding.DER)
def mk(cn, serial):
    k = rsa.generate_private_key(65537, 1024)
    c = (x509.CertificateBuilder().subject_name(name(cn)).issuer_name(name(cn)).public_key(k.public_key())
         .serial_number(serial).not_valid_before(D(2020,1,1)).not_valid_after(D(2060,1,1)).sign(k, hashes.SHA256()))
    return k, c
def le(n, ln): return n.to_bytes(ln, 'little')
def blob(k, alg=0xa400):
    n = k.private_numbers(); p = n.public_numbers
    hdr = bytes([7,2,0,0]) + le(alg,4) + b"RSA2" + le(1024,4) + le(p.e,4)
    return hdr + le(p.n,128) + le(n.p,64) + le(n.q,64) + le(n.dmp1,64) + le(n.dmq1,64) + le(n.iqmp,64) + le(n.d,128)
def pubblob(k, alg=0xa400):
    p = k.public_key().public_numbers()
    return bytes([6,2,0,0]) + le(alg,4) + b"RSA1" + le(1024,4) + le(p.e,4) + le(p.n,128)

k1, c1 = mk("CryptT Msg Signer 1", 0x2001)
k2, c2 = mk("CryptT Msg Signer 2", 0x2002)
arr("V_CONTENT", CONTENT)
arr("V_KEY1", blob(k1)); arr("V_CERT1", der(c1)); arr("V_PUB1", pubblob(k1))
arr("V_KEY2", blob(k2)); arr("V_CERT2", der(c2))
# deterministic raw signatures over CONTENT (PKCS#1 v1.5) for encode-side byte search
for hn, h in (("SHA1", hashes.SHA1()), ("SHA256", hashes.SHA256())):
    arr("V_SIG1_%s" % hn, k1.sign(CONTENT, padding.PKCS1v15(), h))
arr("V_SHA1", hashlib.sha1(CONTENT).digest()); arr("V_SHA256", hashlib.sha256(CONTENT).digest())
arr("V_MD5", hashlib.md5(CONTENT).digest())

td = tempfile.mkdtemp()
def w(n, b): open(os.path.join(td, n), "wb").write(b); return os.path.join(td, n)
w("c1.pem", c1.public_bytes(serialization.Encoding.PEM))
w("k1.pem", k1.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
w("c2.pem", c2.public_bytes(serialization.Encoding.PEM))
w("k2.pem", k2.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
w("in.bin", CONTENT)
def cms(args, nm):
    o = os.path.join(td, nm + ".der")
    subprocess.check_call(["openssl", "cms"] + args + ["-in", os.path.join(td, "in.bin"), "-binary", "-outform", "DER", "-out", o],
                          stderr=subprocess.DEVNULL)
    arr(nm, open(o, "rb").read())
S = ["-sign", "-signer", td + "/c1.pem", "-inkey", td + "/k1.pem", "-md", "sha256"]
cms(S + ["-nodetach"], "M_SIGNED_ATTR")
cms(S + ["-nodetach", "-noattr"], "M_SIGNED_NOATTR")
cms(S + ["-nodetach", "-noattr", "-md", "sha1"], "M_SIGNED_NOATTR_SHA1")
cms(S, "M_SIGNED_DETACHED")
cms(S + ["-noattr"], "M_SIGNED_DETACHED_NOATTR")
cms(S + ["-nodetach", "-nocerts"], "M_SIGNED_NOCERTS")
cms(S + ["-nodetach", "-econtent_type", "1.2.3.4.5.6"], "M_SIGNED_ECT")
cms(S + ["-nodetach", "-signer", td + "/c2.pem", "-inkey", td + "/k2.pem"], "M_SIGNED_TWO")
cms(["-encrypt", "-aes128", "-recip", td + "/c1.pem"], "M_ENV_AES128")
cms(["-encrypt", "-aes256", "-recip", td + "/c1.pem"], "M_ENV_AES256")
cms(["-encrypt", "-des3", "-recip", td + "/c1.pem"], "M_ENV_3DES")
cms(["-digest_create", "-md", "sha256"], "M_DIGESTED_SHA256")
cms(["-digest_create", "-md", "sha1"], "M_DIGESTED_SHA1")
cms(["-data_create"], "M_DATA")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h"), "w").write(
    "/* generated by gen_vectors.py - do not edit */\n#pragma once\n" + "\n".join(out) + "\n")
