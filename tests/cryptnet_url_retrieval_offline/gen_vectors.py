#!/usr/bin/env python3
# Authoring-time generator for vectors.h (needs openssl CLI). Output is checked in.
import subprocess, tempfile, os, re, sys
W = tempfile.mkdtemp()
def sh(cmd, **kw): subprocess.run(cmd, shell=True, check=True, cwd=W, stdout=subprocess.DEVNULL, stderr=None, **kw)
def rd(p): return open(os.path.join(W, p), 'rb').read()
out = ["/* generated by gen_vectors.py - do not edit */\n"]
def arr(name, data):
    out.append("static const unsigned char %s[] = {" % name)
    for i in range(0, len(data), 12):
        out.append("  " + ",".join("0x%02x" % b for b in data[i:i+12]) + ",")
    out.append("};\n")

def mkcert(name, ext, cn):
    sh("openssl ecparam -name prime256v1 -genkey -noout -out %s.key" % name)
    open(os.path.join(W, name + ".cnf"), "w").write(
        "[req]\ndistinguished_name=dn\nprompt=no\nx509_extensions=ext\n[dn]\nCN=%s\n[ext]\n%s\n" % (cn, ext))
    sh("openssl req -new -x509 -key %s.key -days 36500 -set_serial 0x1001 -config %s.cnf -out %s.pem -sha256" % (name, name, name))
    sh("openssl x509 -in %s.pem -outform DER -out %s.der" % (name, name))

# A: full set of URL extensions, doubles as CA for the CRL
extA = """basicConstraints=CA:TRUE
keyUsage=keyCertSign,cRLSign
authorityInfoAccess=OCSP;URI:http://ocsp.example.test/ocsp,caIssuers;URI:http://ca.example.test/ca1.cer,caIssuers;URI:ldap://ldap.example.test/CN=CA?cACertificate?base
crlDistributionPoints=URI:http://crl.example.test/a.crl,URI:ldap://ldap.example.test/CN=CA?certificateRevocationList?base,URI:http://crl2.example.test/b.crl
freshestCRL=URI:http://delta.example.test/d.crl"""
mkcert("a", extA, "cryptt url cert A")
mkcert("b", "basicConstraints=CA:FALSE", "cryptt url cert B")
mkcert("c", "authorityInfoAccess=OCSP;URI:http://ocsp.example.test/only", "cryptt url cert C")
mkcert("d", "crlDistributionPoints=URI:http://crl.example.test/only.crl", "cryptt url cert D")
mkcert("e", "authorityInfoAccess=caIssuers;URI:http://ca.example.test/only.cer", "cryptt url cert E")

# CRL signed by A
sh("mkdir -p ca && touch ca/index.txt && echo 01 > ca/crlnumber")
open(os.path.join(W, "ca.cnf"), "w").write(
    "[ca]\ndefault_ca=c\n[c]\ndatabase=ca/index.txt\ncrlnumber=ca/crlnumber\ndefault_md=sha256\ndefault_crl_days=36500\n")
sh("openssl ca -config ca.cnf -cert a.pem -keyfile a.key -gencrl -crldays 36500 -out a.crl.pem")
sh("openssl crl -in a.crl.pem -outform DER -out a.crl.der")
sh("openssl crl2pkcs7 -nocrl -certfile a.pem -certfile b.pem -outform DER -out ab.p7b")
sh("openssl crl2pkcs7 -nocrl -certfile a.pem -outform DER -out a.p7b")
sh("openssl crl2pkcs7 -in a.crl.pem -outform DER -out crl.p7b")
for n in "abcde": arr("v_cert_" + n, rd(n + ".der"))
arr("v_crl_a", rd("a.crl.der"))
arr("v_p7_ab", rd("ab.p7b"))
arr("v_p7_a", rd("a.p7b"))
# CTL: reuse a deterministic signed CTL from the revocation corpus (authoring-time copy)
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crypt32_crl_ctl_revocation", "vectors.h")).read()
m = re.search(r"static const unsigned char v_ctl_signed\[\] = \{(.*?)\};", src, re.S)
out.append("static const unsigned char v_ctl_signed[] = {" + m.group(1) + "};\n")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h"), "w").write("\n".join(out))
