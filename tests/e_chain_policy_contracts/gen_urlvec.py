#!/usr/bin/env python3
# Authoring-time generator for urlvec.h (offline fixtures whose certificates carry distribution-point and
# authority-information-access URLs under example.invalid).  Output is checked in.
import datetime
from cryptography import x509
from cryptography.x509.oid import NameOID, ExtendedKeyUsageOID as E, AuthorityInformationAccessOID as A
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa

D = datetime.datetime
der = lambda o: o.public_bytes(serialization.Encoding.DER)
key = lambda: rsa.generate_private_key(65537, 2048)
nm = lambda cn: x509.Name([x509.NameAttribute(NameOID.ORGANIZATION_NAME, "CryptT Contracts"), x509.NameAttribute(NameOID.COMMON_NAME, cn)])
U = x509.UniformResourceIdentifier
def cdp(u): return x509.CRLDistributionPoints([x509.DistributionPoint([U(u)], None, None, None)])
def aia(u): return x509.AuthorityInformationAccess([x509.AccessDescription(A.CA_ISSUERS, U(u))])
out = []
def mk(cname, cn, k, issuer, ik, ca, extra=(), serial=None):
    b = (x509.CertificateBuilder().subject_name(nm(cn)).issuer_name(issuer if issuer is not None else nm(cn))
         .public_key(k.public_key()).serial_number(serial or 0x3000 + len(out))
         .not_valid_before(D(2020, 1, 1)).not_valid_after(D(2049, 1, 1))
         .add_extension(x509.BasicConstraints(ca=ca, path_length=0 if ca and issuer is not None else None), critical=True))
    if ca: b = b.add_extension(x509.KeyUsage(False, False, False, False, False, True, True, False, False), critical=True)
    else: b = b.add_extension(x509.ExtendedKeyUsage([E.SERVER_AUTH]), critical=False)
    for e in extra: b = b.add_extension(e, critical=False)
    c = b.sign(ik or k, hashes.SHA256()); out.append((cname, der(c))); return c
kr, ki, km, kl = key(), key(), key(), key()
root = mk("root", "CryptT Contracts Root", kr, None, None, True)
inter = mk("inter", "CryptT Contracts Intermediate", ki, root.subject, kr, True, [cdp("http://example.invalid/inter.crl")])
mk("leaf", "www.example.test", kl, inter.subject, ki, False, [cdp("http://example.invalid/leaf.crl"), aia("http://example.invalid/inter.cer")])
mname = nm("CryptT Contracts Missing Intermediate")
mk("orphan", "orphan.example.test", key(), mname, km, False, [cdp("http://example.invalid/orphan.crl"), aia("http://example.invalid/missing.cer")])
def arr(n, b):
    return "static const unsigned char %s[] = {" % n + ",".join(("\n" if i % 16 == 0 else "") + "0x%02x" % x for i, x in enumerate(b)) + "};\n"
h = "/* generated by gen_urlvec.py - do not edit */\n"
for n, b in out: h += arr("u_" + n, b)
h += "enum {" + ",".join("U_" + n.upper() for n, _ in out) + ",U__COUNT};\n"
h += "static const struct { const unsigned char *p; unsigned n; } g_ucerts[] = {" + ",".join("{u_%s, sizeof u_%s}" % (n, n) for n, _ in out) + "};\n"
open("urlvec.h", "w").write(h)
