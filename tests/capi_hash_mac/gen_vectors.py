def hmac_g(alg, key, msg):
    f = H[alg][1]; bs = H[alg][3]
    if len(key) > bs: key = f(key)
    key = key.ljust(bs, b'\0')
    return f(bytes(b ^ 0x5c for b in key) + f(bytes(b ^ 0x36 for b in key) + msg))
