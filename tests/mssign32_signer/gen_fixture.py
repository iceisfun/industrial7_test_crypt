#!/usr/bin/env python3
"""Authoring-time generator for fixture_data.h (two RSA keys, self-signed code signing certs)."""
import datetime, sys
from cryptography import x509
from cryptography.x509.oid import NameOID, ExtendedKeyUsageOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa

def le(n, size): return n.to_bytes(size, "little")

def blob(key, alg):
    pn = key.private_numbers(); pub = pn.public_numbers
    bits = pub.n.bit_length(); bits = (bits + 7) // 8 * 8
    b = bytes([7, 2, 0, 0]) + le(alg, 4) + b"RSA2" + le(bits, 4) + le(pub.e, 4)
    b += le(pub.n, bits // 8) + le(pn.p, bits // 16) + le(pn.q, bits // 16)
    b += le(pn.dmp1, bits // 16) + le(pn.dmq1, bits // 16) + le(pn.iqmp, bits // 16) + le(pn.d, bits // 8)
    return b

def mk(bits, cn):
    key = rsa.generate_private_key(65537, bits)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
        .serial_number(x509.random_serial_number() >> 64 | 1)
        .not_valid_before(datetime.datetime(2020, 1, 1)).not_valid_after(datetime.datetime(2120, 1, 1))
        .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.CODE_SIGNING]), False)
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), True)
        .sign(key, hashes.SHA256()))
    return key, cert.public_bytes(serialization.Encoding.DER)

def arr(name, data):
    out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        out.append("  " + ",".join("0x%02x" % c for c in data[i:i+16]) + ",")
    out.append("};")
    return "\n".join(out)

o = ["/* generated by gen_fixture.py at authoring time: do not edit */"]
for tag, bits, cn in (("A", 2048, "cryptt mssign32 test A"), ("B", 1024, "cryptt mssign32 test B")):
    k, der = mk(bits, cn)
    o.append(arr("FX_%s_CERT" % tag, der))
    o.append(arr("FX_%s_KEYBLOB" % tag, blob(k, 0xA400)))
    if tag == "A":
        from cryptography.hazmat.primitives.asymmetric import padding
        sig = k.sign(b"abc", padding.PKCS1v15(), hashes.SHA1())
        o.append(arr("FX_A_SIG_SHA1_ABC", sig[::-1]))   # CryptoAPI signatures are little endian
print("\n".join(o))
