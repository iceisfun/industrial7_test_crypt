#!/usr/bin/env python3
# Generates vectors.h: four self-signed RSA-2048 certificates and one CRL (issued by cert 0).
import subprocess, tempfile, os, hashlib, textwrap
d = tempfile.mkdtemp()
def sh(*a, **k): subprocess.check_call(a, cwd=d, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **k)
out = ["/* generated by gen_vectors.py - do not edit */", "#ifndef DS_VECTORS_H", "#define DS_VECTORS_H"]
def arr(name, b):
    body = ",".join("0x%02x" % x for x in b)
    out.append("static const unsigned char %s[] = {%s};" % (name, "\n".join(textwrap.wrap(body, 110))))
names = ["A", "B", "C", "D"]
for i, n in enumerate(names):
    sh("openssl","req","-x509","-newkey","rsa:2048","-nodes","-keyout","k%d.pem"%i,"-out","c%d.pem"%i,
       "-subj","/CN=cryptt system store %s/O=corpus"%n,"-days","36500","-sha256","-set_serial",str(1000+i))
    sh("openssl","x509","-in","c%d.pem"%i,"-outform","DER","-out","c%d.der"%i)
    b = open(os.path.join(d,"c%d.der"%i),"rb").read()
    arr("ds_cert%d_der"%i, b)
    out.append('static const char ds_cert%d_sha1[] = "%s";' % (i, hashlib.sha1(b).hexdigest().upper()))
    out.append('static const wchar_t ds_cert%d_cn[] = L"cryptt system store %s";' % (i, n))
open(os.path.join(d,"ca.cnf"),"w").write("[ca]\ndefault_ca=x\n[x]\ndatabase=idx\ncrlnumber=cn\ndefault_md=sha256\ndefault_crl_days=36000\n")
open(os.path.join(d,"idx"),"w").close(); open(os.path.join(d,"cn"),"w").write("01\n")
sh("openssl","ca","-config","ca.cnf","-gencrl","-keyfile","k0.pem","-cert","c0.pem","-out","crl.pem")
sh("openssl","crl","-in","crl.pem","-outform","DER","-out","crl.der")
arr("ds_crl_der", open(os.path.join(d,"crl.der"),"rb").read())
out.append("#endif")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"vectors.h"),"w").write("\n".join(out)+"\n")
