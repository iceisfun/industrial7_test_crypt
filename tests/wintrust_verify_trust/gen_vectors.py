"""Authoring-time generator for vectors.h: hand-derived DER encodings (Authenticode / catalog ASN.1 modules)
used as known answers for the WVTAsn1* encode/decode pairs.  python3 gen_vectors.py > vectors.h"""
import struct
from gen_fixtures import tlv, seq, oid, octets, integer, carr, NULL
def bmp(s): return s.encode('utf-16-be')
def spc_string(s): return tlv(0x80, bmp(s))                       # unicode [0] IMPLICIT BMPString
def link_url(u): return tlv(0x80, u.encode())                      # url [0] IMPLICIT IA5String
def link_file(f): return tlv(0xA2, spc_string(f))                  # file [2] EXPLICIT SpcString
def link_moniker(cls, data): return tlv(0xA1, octets(cls) + octets(data))  # moniker [1] IMPLICIT SEQUENCE
OUT = {}
